package spire

import (
	"encoding/json"
	"errors"
	"fmt"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/zextras/service-discover/pkg/exec"
)

const (
	// spiffeIDFlag is the spire-server flag carrying the SPIFFE ID of the entry or of the join token.
	spiffeIDFlag = "-spiffeID"
	// outputFlag is the spire-server flag choosing the format of the output of a command.
	outputFlag = "-output"
	// nodePathPrefix starts the path of the SPIFFE ID of a node, see NodeID.
	nodePathPrefix = "/node/"
)

var (
	errTokenNotFound = errors.New("spire-server did not return a join token")
	errNotHealthy    = errors.New("spire-server is not healthy")
)

// ServerCLI drives the spire-server binary through its local API socket. Commands are created through Command so
// that callers can inject their own executor.
type ServerCLI struct {
	Command    func(name string, args ...string) exec.Cmd
	SocketPath string
}

// NewServerCLI returns a ServerCLI talking to the default SPIRE server socket.
func NewServerCLI(command func(name string, args ...string) exec.Cmd) *ServerCLI {
	return &ServerCLI{Command: command, SocketPath: ServerSocket}
}

// WaitHealthy blocks until spire-server answers its health check or the timeout expires.
func (s *ServerCLI) WaitHealthy(timeout, interval time.Duration) error {
	deadline := time.Now().Add(timeout)

	for {
		_, err := s.run("spire-server healthcheck failed", "healthcheck")
		if err == nil {
			return nil
		}

		if time.Now().After(deadline) {
			return fmt.Errorf("%w: %w", errNotHealthy, err)
		}

		time.Sleep(interval)
	}
}

// GenerateJoinToken creates a one-time join token that makes the agent using it attest as spiffeID.
func (s *ServerCLI) GenerateJoinToken(spiffeID string, ttl time.Duration) (string, error) {
	seconds := max(int64((ttl+time.Second-1)/time.Second), 1)

	out, err := s.run("unable to generate a SPIRE join token", "token", "generate",
		spiffeIDFlag, spiffeID, "-ttl", strconv.FormatInt(seconds, 10), outputFlag, "json")
	if err != nil {
		return "", err
	}

	token := struct {
		Value string `json:"value"`
	}{}

	err = json.Unmarshal(out, &token)
	if err != nil {
		return "", fmt.Errorf("unable to decode the join token generated by spire-server: %w", err)
	}

	if strings.TrimSpace(token.Value) == "" {
		return "", errTokenNotFound
	}

	return token.Value, nil
}

// HasEntry reports whether a registration entry binding spiffeID under parentID exists.
func (s *ServerCLI) HasEntry(parentID, spiffeID string) (bool, error) {
	out, err := s.run("unable to list the SPIRE entries", "entry", "show",
		"-parentID", parentID, spiffeIDFlag, spiffeID, outputFlag, "json")
	if err != nil {
		return false, err
	}

	existing := struct {
		Entries []json.RawMessage `json:"entries"`
	}{}

	err = json.Unmarshal(out, &existing)
	if err != nil {
		return false, fmt.Errorf("unable to decode the SPIRE entries: %w", err)
	}

	return len(existing.Entries) > 0, nil
}

// EnsureEntry creates the registration entry binding spiffeID to the given selectors under parentID, unless an
// entry with the same parent and SPIFFE ID already exists. It reports whether the entry has been created.
func (s *ServerCLI) EnsureEntry(parentID, spiffeID string, selectors ...string) (bool, error) {
	exists, err := s.HasEntry(parentID, spiffeID)
	if err != nil {
		return false, err
	}

	if exists {
		return false, nil
	}

	args := []string{"entry", "create", "-parentID", parentID, spiffeIDFlag, spiffeID}
	for _, selector := range selectors {
		args = append(args, "-selector", selector)
	}

	_, err = s.run("unable to create the SPIRE entry for "+spiffeID, args...)
	if err != nil {
		// Another server registered it between the check and the creation: it exists, which is what is wanted.
		if strings.Contains(err.Error(), "AlreadyExists") {
			return false, nil
		}

		return false, err
	}

	return true, nil
}

// NodeHosts returns the names of the hosts of the nodes known to the SPIRE server, sorted: the ones whose join token
// has been generated for a node SPIFFE ID (see NodeID). The services of every one of them need their identities.
func (s *ServerCLI) NodeHosts() ([]string, error) {
	out, err := s.run("unable to list the SPIRE entries", "entry", "show", outputFlag, "json")
	if err != nil {
		return nil, err
	}

	existing := struct {
		Entries []struct {
			SpiffeID struct {
				Path string `json:"path"`
			} `json:"spiffe_id"`
		} `json:"entries"`
	}{}

	err = json.Unmarshal(out, &existing)
	if err != nil {
		return nil, fmt.Errorf("unable to decode the SPIRE entries: %w", err)
	}

	seen := map[string]bool{}

	var hosts []string

	for _, entry := range existing.Entries {
		host, isNode := strings.CutPrefix(entry.SpiffeID.Path, nodePathPrefix)
		if isNode && host != "" && !seen[host] {
			seen[host] = true

			hosts = append(hosts, host)
		}
	}

	slices.Sort(hosts)

	return hosts, nil
}

// BundlePEM returns the trust bundle of the SPIRE server in PEM format.
func (s *ServerCLI) BundlePEM() (string, error) {
	out, err := s.run("unable to read the SPIRE trust bundle", "bundle", "show")
	if err != nil {
		return "", err
	}

	return strings.TrimSpace(string(out)) + "\n", nil
}

func (s *ServerCLI) run(reason string, args ...string) ([]byte, error) {
	args = append(args, "-socketPath", s.SocketPath)

	out, err := s.Command(ServerBin, args...).Output()
	if err != nil {
		return nil, exec.ErrorFromStderr(err, reason)
	}

	return out, nil
}
